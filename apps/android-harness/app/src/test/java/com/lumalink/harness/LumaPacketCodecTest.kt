    @Test
    fun testExtractMultipleByteSegmentsConcatenatedInOrder() {
        val seg1 = PHASE_5B_PACKET_0.copyOfRange(0, 50)
        val seg2 = PHASE_5B_PACKET_0.copyOfRange(50, 122)

        val result = Result("ignored", null, emptyArray<ResultPoint>(), BarcodeFormat.QR_CODE)
        result.putMetadata(ResultMetadataType.BYTE_SEGMENTS, listOf(seg1, seg2))

        val extracted = QrBytePayloadExtractor.extract(result)
        assertNotNull(extracted)
        assertEquals(122, extracted!!.size)
        assertArrayEquals(PHASE_5B_PACKET_0, extracted)

        // Verify the extracted bytes decode as a valid packet
        val packet = LumaPacketCodec.decode(extracted)
        assertEquals(0x0d2f3c6fL, packet.crc32)
        assertEquals(0L, packet.symbolId)
    }

    @Test
    fun testBinaryBytesGreaterThan0x80SurviveWithoutUtf8Corruption() {
        val highBytes = byteArrayOf(0x80.toByte(), 0x90.toByte(), 0xFE.toByte(), 0xFF.toByte(), 0xDE.toByte())
        val result = Result("ignored", null, emptyArray<ResultPoint>(), BarcodeFormat.QR_CODE)
        result.putMetadata(ResultMetadataType.BYTE_SEGMENTS, listOf(highBytes))

        val extracted = QrBytePayloadExtractor.extract(result)
        assertNotNull(extracted)
        assertArrayEquals(highBytes, extracted)

        // Compare with what UTF-8 would have produced: UTF-8 conversion corrupts high bytes
        val utf8Mangled = String(highBytes, Charsets.UTF_8).toByteArray(Charsets.UTF_8)
        assertFalse(
            "Direct BYTE_SEGMENTS extraction must not produce mangled UTF-8 bytes",
            extracted.contentEquals(utf8Mangled)
        )
    }

