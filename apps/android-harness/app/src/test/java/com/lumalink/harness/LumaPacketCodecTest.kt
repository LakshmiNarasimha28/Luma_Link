    @Test
    fun testGoldenVectorPacket0Parity() {
        val packet = LumaPacketCodec.decode(PHASE_5B_PACKET_0)

        // Verify exact header layout fields matching Canonical TS BinaryPacketCodec:
        assertEquals("Protocol version must be 1", 1, packet.version)
        assertEquals("Packet type DATA must be 2", 2, packet.packetType)
        assertEquals("FLAG_ENCRYPTED must be 2", 2, packet.flags)
        assertEquals("Reserved byte must be 0", 0, packet.reserved)
        assertEquals("Session UUID must match fixture manifest", EXPECTED_SESSION_ID, packet.sessionIdUuid)
        assertEquals("Block index must be 0", 0L, packet.blockIndex)
        assertEquals("Symbol ID must be 0", 0L, packet.symbolId)
        assertEquals("Source symbols K must be 16", 16, packet.k)
        assertEquals("LT degree must be 1", 1, packet.degree)
        assertEquals("Payload length must be 80", 80, packet.payloadLength)
        assertEquals("Transmitted CRC must be 0x0d2f3c6f", 0x0d2f3c6fL, packet.crc32)

        // Verify standalone CRC-32 computation
        val computedCrc = LumaPacketCodec.computePacketChecksum(PHASE_5B_PACKET_0, 80)
        assertEquals("Computed CRC must match transmitted CRC", 0x0d2f3c6fL, computedCrc)

        // Verify raw bytes
        assertEquals(122, packet.rawBytes.size)
        assertArrayEquals(PHASE_5B_PACKET_0, packet.rawBytes)
    }

