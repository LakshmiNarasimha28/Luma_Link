    // =========================================================================
    // H. Unsigned Byte Values Test (bytes >= 0x80 and 0xFF)
    // =========================================================================

    @Test
    fun testUnsignedBytesSurviveUnchanged() {
        val testPayload = ByteArray(10) { i ->
            when (i) {
                0 -> 0x80.toByte() // 128
                1 -> 0xFF.toByte() // 255
                2 -> 0xFE.toByte() // 254
                3 -> 0xAA.toByte() // 170
                4 -> 0x7F.toByte() // 127
                5 -> 0x00.toByte() // 0
                else -> (0x80 + i).toByte()
            }
        }

        // Construct synthetic valid packet with high-byte payload
        val raw = ByteArray(42 + testPayload.size)
        val buf = ByteBuffer.wrap(raw).order(ByteOrder.BIG_ENDIAN)
        raw[0] = 0x4C; raw[1] = 0x55; raw[2] = 0x4D; raw[3] = 0x41 // 'LUMA'
        raw[4] = 1 // version 1
        raw[5] = 2 // DATA
        raw[6] = 0x82.toByte() // flags with high bit set (130)
        raw[7] = 0 // reserved
        for (i in 0 until 16) raw[8 + i] = (0x90 + i).toByte()
        buf.putInt(24, 1000)
        buf.putInt(28, 500)
        buf.putShort(32, 16.toShort())
        buf.putShort(34, 1.toShort())
        buf.putShort(36, testPayload.size.toShort())
        System.arraycopy(testPayload, 0, raw, 42, testPayload.size)

        // Compute valid CRC
        val crc = LumaPacketCodec.computePacketChecksum(raw, testPayload.size)
        buf.putInt(38, (crc and 0xFFFFFFFFL).toInt())

        val packet = LumaPacketCodec.decode(raw)
        assertEquals(0x82, packet.flags)
        assertEquals(128, packet.payload[0].toInt() and 0xFF)
        assertEquals(255, packet.payload[1].toInt() and 0xFF)
        assertEquals(254, packet.payload[2].toInt() and 0xFF)
        assertEquals(170, packet.payload[3].toInt() and 0xFF)
        assertArrayEquals(testPayload, packet.payload)
    }

    // =========================================================================
    // I. Big-Endian Fields Parsing Test
    // =========================================================================

    @Test
    fun testBigEndianFieldParsing() {
        val raw = ByteArray(42)
        val buf = ByteBuffer.wrap(raw).order(ByteOrder.BIG_ENDIAN)
        raw[0] = 0x4C; raw[1] = 0x55; raw[2] = 0x4D; raw[3] = 0x41
        raw[4] = 1; raw[5] = 2; raw[6] = 0; raw[7] = 0

        // Asymmetric values to detect endian inversion
        val testBlockIndex = 0x12345678L
        val testSymbolId = 0x89ABCDEFL // High bit set: 2,309,737,967L
        val testK = 0xFEDC // 65244
        val testDegree = 0x4321 // 17185
        val testPayloadLen = 0

        buf.putInt(24, (testBlockIndex and 0xFFFFFFFFL).toInt())
        buf.putInt(28, (testSymbolId and 0xFFFFFFFFL).toInt())
        buf.putShort(32, (testK and 0xFFFF).toShort())
        buf.putShort(34, (testDegree and 0xFFFF).toShort())
        buf.putShort(36, testPayloadLen.toShort())

        val crc = LumaPacketCodec.computePacketChecksum(raw, testPayloadLen)
        buf.putInt(38, (crc and 0xFFFFFFFFL).toInt())

        val packet = LumaPacketCodec.decode(raw)
        assertEquals(0x12345678L, packet.blockIndex)
        assertEquals(0x89ABCDEFL, packet.symbolId)
        assertEquals(0xFEDC, packet.k)
        assertEquals(0x4321, packet.degree)
        assertEquals(0, packet.payloadLength)
        assertEquals(crc, packet.crc32)
    }

